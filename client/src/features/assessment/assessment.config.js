/** Which conditional health blocks apply (based on answers and the selected program). */
export function relevance(values, track) {
  const c = values.health?.conditions ?? [];
  return {
    pcos: c.includes('pcos') || track.pcos,
    diabetes: c.includes('diabetes'),
    thyroid: c.includes('thyroid'),
    digestive: c.includes('digestive') || track.gut,
    otherCondition: c.includes('other'),
    dietOther: values.nutrition?.dietaryPreference === 'other',
    otherGoal: (values.goals?.goals ?? []).includes('other'),
  };
}
